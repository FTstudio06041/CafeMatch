# 確認需求
def get_confirmation_instruction(summary, next_dim_label, question_count, max_questions,
                                 latest_user_msg="", examples=None, quick_options=None):
    """
    產生「確認使用者需求」的引導指令。

    讓 AI 順著使用者剛說的話「接話」，把下一個不確定維度的確認問題
    自然編進對話劇情裡，而不是制式地逐項問卷；
    確認後的偏好會回流到狀態機決定何時邀請推薦。
    """
    instruction = (
        f"【任務】順著這輪需求，確認「{next_dim_label}」。不要推薦店家。\n"
        f"目前已知的偏好：{summary}。\n"
    )
    if latest_user_msg:
        instruction += f"使用者剛剛說：「{latest_user_msg}」。\n"
    instruction += (
        f"順著他剛剛的話接一句，把「{next_dim_label}」的問題自然編進去"
        f"（例如他說要跟朋友聚會，就問「聚會想要什麼氛圍」），不要突兀換話題。\n"
        f"只問一個問題，問完就停。\n"
        "如果使用者同時提問，先回答；如果他改口，先確認最新條件，別沿用已取消的偏好。\n"
        "問題要和這次情境有關，已經明確說過的條件不要再問，不能把問法靈感當固定台詞。\n"
        + BREVITY_RULE + "\n"
        f"【目前進度】已提問 {question_count} / 上限 {max_questions}。\n"
    )
    if quick_options:
        opts = " | ".join(quick_options[:4])
        instruction += (
            f"【選項格式】回覆的最後請另起一行，原封不動加上這一行：\n"
            f"[QUICK_OPTIONS] {opts}"
        )
    else:
        instruction += QUICK_OPTIONS_FORMAT
    examples = [e for e in (examples or []) if e]
    if examples:
        examples_text = "\n".join(f"- {e}" for e in examples)
        instruction += (
            f"\n\n【問法靈感（絕對禁止照抄，一定要換句話說、並結合上面的對話脈絡）】\n"
            f"{examples_text}"
        )
    return instruction

